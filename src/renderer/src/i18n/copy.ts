export type CopyKey = keyof typeof zh
export type CopyValues = Record<string, string | number>

export function resolveLocale(preferred?: string): Locale {
  return preferred?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

export function createTranslator(locale: Locale): (key: CopyKey, values?: CopyValues) => string {
  const messages = locale === 'zh-CN' ? zh : en
  return (key, values) => interpolate(messages[key], values)
}

function interpolate(template: string, values: CopyValues = {}): string {
  return template.replaceAll(/\{([A-Za-z0-9_]+)\}/g, (_, name: string) => {
    const value = values[name]
    return value === undefined ? `{${name}}` : String(value)
  })
}
